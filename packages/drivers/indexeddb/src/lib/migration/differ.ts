// idb/migration/differ.ts
import type {
    IDBDatabaseSnapshot,
    IDBFieldSnapshot,
    MigrationOp,
    MigrationPlan,
  } from './types';
  
  export class MigrationDiffer {
  
    static diff(
      old:  IDBDatabaseSnapshot | null,
      next: IDBDatabaseSnapshot,
    ): MigrationPlan {
      const ops:         MigrationOp[] = [];
      const description: string[]      = [];
  
      // ── أول تشغيل ──────────────────────────────────────────
      if (!old) {
        for (const store of Object.values(next.stores)) {
          ops.push({ op: 'CREATE_STORE', store: store.name, keyPath: store.keyPath });
          description.push(`✚ Create store: "${store.name}"`);
  
          for (const index of store.indexes) {
            ops.push({ op: 'CREATE_INDEX', store: store.name, index });
            description.push(`  ✚ Index: "${index.name}" (unique=${index.unique})`);
          }
        }
  
        return {
          fromVersion:           0,
          toVersion:             1,
          ops,
          requiresDataMigration: false,
          description,
        };
      }
  
      // ── Diff ────────────────────────────────────────────────
      let requiresDataMigration = false;
  
      // Stores مضافة
      for (const [name, store] of Object.entries(next.stores)) {
        if (old.stores[name]) continue;
  
        ops.push({ op: 'CREATE_STORE', store: name, keyPath: store.keyPath });
        description.push(`✚ New store: "${name}"`);
  
        for (const index of store.indexes) {
          ops.push({ op: 'CREATE_INDEX', store: name, index });
          description.push(`  ✚ Index: "${index.name}"`);
        }
      }
  
      // Stores محذوفة
      for (const name of Object.keys(old.stores)) {
        if (!next.stores[name]) {
          ops.push({ op: 'DELETE_STORE', store: name });
          description.push(`✖ Deleted store: "${name}"`);
        }
      }
  
      // Stores موجودة في الاثنين
      for (const [name, newStore] of Object.entries(next.stores)) {
        const oldStore = old.stores[name];
        if (!oldStore) continue;
  
        const oldIdx = new Map(oldStore.indexes.map(i => [i.name, i]));
        const newIdx = new Map(newStore.indexes.map(i => [i.name, i]));
  
        // Indexes مضافة
        for (const [idxName, idx] of newIdx) {
          if (!oldIdx.has(idxName)) {
            ops.push({ op: 'CREATE_INDEX', store: name, index: idx });
            description.push(`  ✚ New index: "${name}.${idxName}"`);
            requiresDataMigration = true;
          }
        }
  
        // Indexes محذوفة
        for (const idxName of oldIdx.keys()) {
          if (!newIdx.has(idxName)) {
            ops.push({ op: 'DELETE_INDEX', store: name, indexName: idxName });
            description.push(`  ✖ Removed index: "${name}.${idxName}"`);
          }
        }
  
        // Indexes تغيّر unique أو keyPath
        for (const [idxName, newIndex] of newIdx) {
          const oldIndex = oldIdx.get(idxName);
          if (!oldIndex) continue;
  
          const changed =
            oldIndex.unique     !== newIndex.unique     ||
            oldIndex.keyPath    !== newIndex.keyPath     ||
            oldIndex.multiEntry !== newIndex.multiEntry;
  
          if (changed) {
            ops.push({ op: 'RECREATE_INDEX', store: name, index: newIndex });
            description.push(
              `  ↻ Recreated index: "${name}.${idxName}"` +
              ` (unique: ${oldIndex.unique}→${newIndex.unique})`
            );
          }
        }
  
        // Fields جديدة غير optional بدون auto-generation — تحتاج backfill
        for (const [fieldName, newField] of Object.entries(newStore.fields)) {
          const oldField = oldStore.fields[fieldName];
          if (oldField) continue;                      // موجود قبل
          if (newField.optional || newField.autoGenerated) continue; // لا يحتاج backfill
  
          const defaultVal = this.inferDefault(newField);
          ops.push({
            op:           'ADD_FIELD_DEFAULT',
            store:        name,
            field:        fieldName,
            defaultValue: defaultVal,
          });
          description.push(
            `  ✚ Backfill field: "${name}.${fieldName}" = ${JSON.stringify(defaultVal)}`
          );
          requiresDataMigration = true;
        }
      }
  
      const hasStructural = ops.some(o =>
        o.op === 'CREATE_STORE'  ||
        o.op === 'DELETE_STORE'  ||
        o.op === 'CREATE_INDEX'  ||
        o.op === 'DELETE_INDEX'  ||
        o.op === 'RECREATE_INDEX'
      );
  
      return {
        fromVersion:           old.version,
        toVersion:             hasStructural ? old.version + 1 : old.version,
        ops,
        requiresDataMigration,
        description,
      };
    }
  
    private static inferDefault(field: IDBFieldSnapshot): unknown {
      switch (field.type) {
        case 'string':  return '';
        case 'number':  return 0;
        case 'boolean': return false;
        case 'date':    return new Date().toISOString();
        default:        return null;
      }
    }
  }