// idb/migration/serializer.ts

import { GlobalRegistryOutput, JSONSchemaObject, JSONSchemaProperty } from '@listedbase/core';
import type {
    IDBDatabaseSnapshot,
    IDBStoreSnapshot,
    IDBFieldSnapshot,
    IDBIndexSnapshot,
  } from './types';
  
  // ─────────────────────────────────────────────────────────────
  
  export class SchemaSerializer {
  
    static serialize(registryOutput: GlobalRegistryOutput): IDBDatabaseSnapshot {
      const stores: Record<string, IDBStoreSnapshot> = {};
  
      for (const [schemaId, jsonSchema] of Object.entries(registryOutput.schemas)) {

        const store = this.serializeStore(schemaId, jsonSchema);
        if (store) stores[store.name] = store;
      }
  
      return {
        version:   0,  // يُحسب لاحقاً في الـ differ
        stores,
        createdAt: new Date().toISOString(),
      };
    }
  
    // ── store واحد ──────────────────────────────────────────────
  
    private static serializeStore(
      schemaId:   string,
      jsonSchema: JSONSchemaObject,
    ): IDBStoreSnapshot | null {
      if (jsonSchema.type !== 'object') return null;
  
      const storeName = jsonSchema.name ?? schemaId;
      const fields:  Record<string, IDBFieldSnapshot> = {};
      const indexes: IDBIndexSnapshot[]               = [];
      let   keyPath  = 'id'; // fallback
      let   autoIncrement = false
      for (const [fieldName, prop] of Object.entries(jsonSchema.properties)) {
        const field = this.serializeField(fieldName, prop, jsonSchema.required ?? []);
        fields[fieldName] = field;
  
        // primary key
        if (prop.idField) {
          keyPath = fieldName;
          autoIncrement = prop.autoIncrement ?? false; // ← جديد
        }
  
        // index entries
        if (prop.unique || prop.index) {
          indexes.push({
            name:       `idx_${fieldName}`,
            keyPath:    fieldName,
            unique:     prop.unique ?? false,
            multiEntry: false,
          });
        }
  
        // relation — $ref يعني FK، نضيف index للـ FK
        if (prop.$ref) {
          const fkFieldName = `${fieldName}Id`;
          indexes.push({
            name:       `idx_${fkFieldName}`,
            keyPath:    fkFieldName,
            unique:     false,
            multiEntry: false,
          });
        }
  
        // many relation — array of $ref — نضيف multiEntry index
        if (prop.type === 'array' && prop.items?.$ref) {
          indexes.push({
            name:       `idx_${fieldName}`,
            keyPath:    `${fieldName}Ids`,
            unique:     false,
            multiEntry: true,  // multiEntry للـ one-to-many
          });
        }
      }
  
      return { name: storeName, keyPath, autoIncrement, fields, indexes };
    }
  
    // ── field واحد ──────────────────────────────────────────────
  
    private static serializeField(
      fieldName: string,
      prop:      JSONSchemaProperty,
      required:  string[],
    ): IDBFieldSnapshot {
      return {
        name:          fieldName,
        type:          this.resolveType(prop),
        unique:        prop.unique        ?? false,
        indexed:       prop.index         ?? prop.unique ?? false,
        optional:      !required.includes(fieldName),
        autoGenerated: prop.autogen       ?? false,
      };
    }
  
    // ── type resolution ─────────────────────────────────────────
  
    private static resolveType(prop: JSONSchemaProperty): IDBFieldSnapshot['type'] {
      // relation — $ref مباشر (one-to-one / many-to-one)
      if (prop.$ref) return 'relation-one';
  
      // relation — array of $ref (one-to-many)
      if (prop.type === 'array' && prop.items?.$ref) return 'relation-many';
  
      // nullable — anyOf: [{ type: 'X' }, { type: 'null' }]
      // أو updatedAt — anyOf: [{ type: 'string', format: 'date-time' }, { type: 'null' }]
      if (prop.anyOf) {
        const nonNull = prop.anyOf.find(p => p.type !== 'null' && !('type' in p === false));
        if (nonNull) return this.resolveType(nonNull);
      }
  
      // primary key أو id field
      if (prop.idField) return 'id';
  
      // date-time strings
      if (prop.type === 'string' && prop.format === 'date-time') return 'date';
  
      // standard types
      switch (prop.type) {
        case 'string':  return 'string';
        case 'number':
        case 'integer': return 'number';
        case 'boolean': return 'boolean';
        default:        return 'string'; // fallback safe
      }
    }
  }