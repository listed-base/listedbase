// idb/migration/types.ts

export interface IDBIndexSnapshot {
    name:       string;
    keyPath:    string;
    unique:     boolean;
    multiEntry: boolean;
  }
  
  export interface IDBFieldSnapshot {
    name:          string;
    type:          'string' | 'number' | 'boolean' | 'date' | 'id'
                   | 'relation-one' | 'relation-many';
    unique:        boolean;
    indexed:       boolean;
    optional:      boolean;
    autoGenerated: boolean;
  }
  
  export interface IDBStoreSnapshot {
    name:          string;
    keyPath:       string;
    autoIncrement: boolean; // ← جديد
    fields:        Record<string, IDBFieldSnapshot>;
    indexes:       IDBIndexSnapshot[];
  }
  
  export interface IDBDatabaseSnapshot {
    version:   number;
    stores:    Record<string, IDBStoreSnapshot>;
    createdAt: string;
  }
  
  export type MigrationOp =
    | { op: 'CREATE_STORE';      store: string; keyPath: string, autoIncrement?: boolean }
    | { op: 'DELETE_STORE';      store: string }
    | { op: 'CREATE_INDEX';      store: string; index: IDBIndexSnapshot }
    | { op: 'DELETE_INDEX';      store: string; indexName: string }
    | { op: 'RECREATE_INDEX';    store: string; index: IDBIndexSnapshot }
    | { op: 'ADD_FIELD_DEFAULT'; store: string; field: string; defaultValue: unknown }
    | { op: 'RENAME_FIELD';      store: string; from: string; to: string }
    | { op: 'DROP_FIELD_DATA';   store: string; field: string }
  
  export interface MigrationPlan {
    fromVersion:           number;
    toVersion:             number;
    ops:                   MigrationOp[];
    requiresDataMigration: boolean;
    description:           string[];
  }