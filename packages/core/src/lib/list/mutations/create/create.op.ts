import { ZodObject } from 'zod/v4';
import { LListContext } from '../../context';
import { CreateOp } from './create.types';
import { runGroup } from '../runtime/runGroup';
import { project } from '../refine/project';
import { MutationPlan } from '../runtime/plan';

function generateAutogenFields(
  schema: ZodObject<any>,
  plan: MutationPlan
): Record<string, any> {
  const generated: Record<string, any> = {};
  const shape = schema.shape;

  for (const key of Object.keys(shape)) {
    const field = shape[key];
    const meta =
      field?.__lMeta || (field?.description ? JSON.parse(field.description) : null);

    if (meta?.idField === true && meta?.autogen === true) {
      if (plan.id === 'core') {
        generated[key] = crypto.randomUUID();
      }
    } else if (meta?.autogen === true && meta?.type === 'date') {
      if (plan.timestamps === 'core') {
        generated[key] = new Date();
      }
    }
  }

  // Fallbacks if not explicitly marked via meta
  if (plan.id === 'core' && !('id' in generated) && 'id' in shape) {
    generated['id'] = crypto.randomUUID();
  }
  if (plan.timestamps === 'core' && !('createdAt' in generated) && 'createdAt' in shape) {
    generated['createdAt'] = new Date();
  }

  return generated;
}

export function createOp<S extends ZodObject<any>>(
  ctx: LListContext<S>
): CreateOp<S> {
  return async (input: any, refine?: any): Promise<any> => {
    return runGroup(
      ctx,
      'create',
      input,
      async (rawItem: any, plan: MutationPlan) => {
        const autogenFields = generateAutogenFields(ctx.schema, plan);

        // Disallow user overrides for autogen values when generated by Core
        const itemWithDefaults = {
          ...rawItem,
          ...autogenFields,
        };

        let parsed: any;
        if (plan.id === 'driver') {
          // When driver handles idGeneration, parse without calling id's default
          delete itemWithDefaults.id;
          const { id: _idField, ...shapeWithoutId } = ctx.schema.shape;
          const partialSchema = (ctx.schema as any).constructor
            ? ctx.schema.pick({ ...Object.keys(shapeWithoutId).reduce((acc: any, k) => ({ ...acc, [k]: true }), {}) } as any)
            : ctx.schema;
          parsed = partialSchema.parse(itemWithDefaults);
        } else {
          parsed = ctx.schema.parse(itemWithDefaults);
        }

        const encoded = ctx.codec.encode(parsed);
        const createdRaw = await ctx.driver().create(ctx.name, encoded);

        let resultRecord =
          plan.returning === 'driver' && createdRaw ? createdRaw : (createdRaw || encoded);

        if (createdRaw && createdRaw.id) {
          resultRecord = { ...resultRecord, id: createdRaw.id };
        }

        return project(
          'create',
          refine?.intent,
          null,
          resultRecord,
          refine?.select,
          ctx.driver(),
          ctx.codec.decode
        );
      },
      refine,
      'DRIVER/UNKNOWN',
      'Create operation failed.'
    );
  };
}
